#!/usr/bin/env python3
"""Build main.js for the Casa Obsidian plugin.

Run from anywhere:  python3 -I build.py [--dist DIR] [--root DIR]

What it does
  1. Bundles the plugin-side CommonJS modules (src/plugin, src/vault, src/integrations)
     into a tiny module registry inside main.js. Each file becomes
     `function (module, exports, require) { ... }`. Relative requires are resolved at
     runtime against the registry; bare requires (`obsidian`) go to the real require.
  2. Builds the room document: src/room/room.html + src/room/room.css + every file
     listed in src/room/order.txt (lines starting with # are skipped, missing files
     only warn). The bridge shim (src/plugin/room-side/shim.js) is the first script.
     src/room/dev/ is never included.
  3. Embeds the room document in main.js as a string (module
     `src/plugin/room-doc.generated.js`).
  4. Checks the syntax of every source file and of main.js with node. Any error
     stops the build with exit code 1.

Only main.js, manifest.json and styles.css reach users, so everything the room
needs must be inside main.js.

Standard library only.
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PLUGIN_DIRS = ("src/plugin", "src/vault", "src/integrations")
ROOM_SIDE_DIR = "src/plugin/room-side"          # browser scripts owned by the shell, not CommonJS
SHIM = "src/plugin/room-side/shim.js"
ROOM_DIR = "src/room"
ROOM_DOC_ID = "src/plugin/room-doc.generated.js"
ENTRY = "src/plugin/main.js"
RELEASE_FILES = ("main.js", "manifest.json", "styles.css")

# The room may not reach the network by itself: every request goes through the
# plugin bridge, so README "Network use" stays complete. Audio and video may
# stream from https (music tracks); images arrive as data: URLs.
ROOM_CSP = (
    "default-src 'none'; "
    "script-src 'unsafe-inline' blob:; "
    "style-src 'unsafe-inline'; "
    "img-src data: blob:; "
    "media-src data: blob: https:; "
    "font-src data:; "
    "connect-src data: blob:; "
    "worker-src blob:"
)

DEFAULT_ROOM_HTML = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Casa</title>
</head>
<body>
<div id="casa-missing" style="font:14px system-ui;padding:24px;color:#888">The room is not built yet.</div>
</body>
</html>
"""

warnings = []


def warn(msg):
    warnings.append(msg)
    print("WARNING: " + msg, file=sys.stderr)


def fail(msg):
    print("ERROR: " + msg, file=sys.stderr)
    sys.exit(1)


def kb(n):
    return "%.1f KB" % (n / 1024.0)


def read(path):
    return Path(path).read_text(encoding="utf-8")


# ---------------------------------------------------------------- plugin modules

def collect_modules(root):
    """All .js / .json files under the plugin-side folders, as repo-relative ids."""
    mods = []
    for d in PLUGIN_DIRS:
        base = root / d
        if not base.is_dir():
            continue
        for p in sorted(base.rglob("*")):
            if not p.is_file():
                continue
            rel = p.relative_to(root).as_posix()
            if rel.startswith(ROOM_SIDE_DIR + "/"):
                continue
            if any(part.startswith(".") for part in p.relative_to(root).parts):
                continue
            if p.suffix not in (".js", ".json") or p.name.endswith(".test.js"):
                continue
            if rel == ROOM_DOC_ID:
                fail(ROOM_DOC_ID + " is generated by build.py; remove the file from src/")
            mods.append(rel)
    return mods


BARE_REQUIRE = re.compile(r"""\brequire\(\s*['"]([^'"./][^'"]*)['"]\s*\)""")


def module_entry(root, rel):
    src = read(root / rel)
    if rel.endswith(".json"):
        try:
            json.loads(src)
        except ValueError as e:
            fail("%s: invalid JSON: %s" % (rel, e))
        body = "module.exports = " + src.strip() + ";"
    else:
        for name in BARE_REQUIRE.findall(src):
            if name != "obsidian":
                warn("%s requires '%s': only 'obsidian' is expected in shipped code" % (rel, name))
        body = src
    return "%s: function (module, exports, require) {\n%s\n}" % (json.dumps(rel), body)


# Runtime registry. Kept small and dependency free; it is the first thing in main.js.
REGISTRY = r"""
var __casaCache = {};
function __casaResolve(fromId, spec) {
  if (spec.charAt(0) !== '.' && spec.charAt(0) !== '/') return null;
  var parts = fromId.split('/'); parts.pop();
  var out = [];
  parts.concat(spec.split('/')).forEach(function (p) {
    if (p === '' || p === '.') return;
    if (p === '..') out.pop(); else out.push(p);
  });
  var id = out.join('/');
  var tries = [id, id + '.js', id + '.json', id + '/index.js'];
  for (var i = 0; i < tries.length; i++) {
    if (Object.prototype.hasOwnProperty.call(__casaFiles, tries[i])) return tries[i];
  }
  return undefined;
}
function __casaRequireFrom(fromId) {
  return function (spec) {
    var id = __casaResolve(fromId, String(spec));
    if (id === null) return require(spec);
    if (id === undefined) {
      var err = new Error("Cannot find module '" + spec + "' from '" + fromId + "'");
      err.code = 'MODULE_NOT_FOUND';
      throw err;
    }
    return __casaLoad(id);
  };
}
function __casaLoad(id) {
  if (__casaCache[id]) return __casaCache[id].exports;
  var mod = { id: id, exports: {} };
  __casaCache[id] = mod;
  try {
    __casaFiles[id].call(mod.exports, mod, mod.exports, __casaRequireFrom(id));
  } catch (e) {
    delete __casaCache[id];
    throw e;
  }
  return mod.exports;
}
"""


# ---------------------------------------------------------------- room document

def read_order(root):
    order = root / ROOM_DIR / "order.txt"
    if not order.is_file():
        warn("src/room/order.txt is missing: the room has no scripts")
        return []
    entries = []
    for n, line in enumerate(read(order).splitlines(), 1):
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        name = s.split()[0]
        if name.startswith("src/room/"):
            name = name[len("src/room/"):]
        if name.startswith("./"):
            name = name[2:]
        if name.startswith("/") or ".." in name.split("/"):
            warn("order.txt line %d: '%s' is outside src/room, skipped" % (n, name))
            continue
        if name == "dev" or name.startswith("dev/"):
            warn("order.txt line %d: '%s' is a dev file, never bundled" % (n, name))
            continue
        entries.append((n, name))
    return entries


def escape_tag(text, tag):
    """Keep inlined code from closing its own <script>/<style> element."""
    text = re.sub(r"</(%s)" % tag, r"<\\/\1", text, flags=re.I)
    if tag == "script":
        text = text.replace("<!--", "<\\!--")
    return text


def build_room(root):
    room = root / ROOM_DIR
    html_path = room / "room.html"
    if html_path.is_file():
        html = read(html_path)
    else:
        warn("src/room/room.html is missing: using a placeholder page")
        html = DEFAULT_ROOM_HTML
    if re.search(r"<script[^>]*\bsrc\s*=", html, re.I):
        warn("room.html has <script src>: the room is a srcdoc iframe, list scripts in order.txt instead")
    if re.search(r"<link[^>]*rel\s*=\s*['\"]?stylesheet", html, re.I):
        warn("room.html links a stylesheet: inline CSS goes in room.css or order.txt")

    styles = []
    css_path = room / "room.css"
    if css_path.is_file():
        styles.append(("room.css", read(css_path)))
    else:
        warn("src/room/room.css is missing")

    scripts = []
    seen = set()
    listed = set()
    for n, name in read_order(root):
        if name in seen:
            warn("order.txt line %d: '%s' listed twice, second skipped" % (n, name))
            continue
        seen.add(name)
        p = room / name
        if not p.is_file():
            warn("order.txt line %d: '%s' not found, skipped" % (n, name))
            continue
        listed.add(p.resolve())
        if name.endswith(".css"):
            if name != "room.css":
                styles.append((name, read(p)))
        elif name.endswith(".js"):
            scripts.append((name, read(p)))
        else:
            warn("order.txt line %d: '%s' is not .js or .css, skipped" % (n, name))

    unlisted = []
    if room.is_dir():
        for p in sorted(room.rglob("*.js")):
            rel = p.relative_to(room).as_posix()
            if rel.startswith("dev/") or p.resolve() in listed:
                continue
            unlisted.append(rel)
    if unlisted:
        print("note: room scripts not in order.txt (not bundled): " + ", ".join(unlisted))

    shim_path = root / SHIM
    if not shim_path.is_file():
        fail(SHIM + " is missing")
    shim = read(shim_path)

    head_bits = [
        '<meta http-equiv="Content-Security-Policy" content="%s">' % ROOM_CSP,
        "<script>\n%s\n//# sourceURL=casa-room/bridge-shim.js\n</script>" % escape_tag(shim, "script"),
    ]
    style_bits = ["<style>/* %s */\n%s\n</style>" % (name, escape_tag(css, "style")) for name, css in styles]
    script_bits = [
        "<script>\n%s\n//# sourceURL=casa-room/%s\n</script>" % (escape_tag(js, "script"), name)
        for name, js in scripts
    ]

    # shim + CSP first in <head>, styles at the end of <head>, scripts at the end of <body>
    m = re.search(r"<head[^>]*>", html, re.I)
    if m:
        html = html[:m.end()] + "\n" + "\n".join(head_bits) + html[m.end():]
    else:
        m = re.search(r"<html[^>]*>", html, re.I) or re.search(r"<!doctype[^>]*>", html, re.I)
        at = m.end() if m else 0
        html = html[:at] + "\n<head>\n" + "\n".join(head_bits) + "\n</head>" + html[at:]

    m = re.search(r"</head\s*>", html, re.I)
    if m:
        html = html[:m.start()] + "\n".join(style_bits) + "\n" + html[m.start():]
    else:
        html = "\n".join(style_bits) + "\n" + html

    m = None
    for m in re.finditer(r"</body\s*>", html, re.I):
        pass
    if m:
        html = html[:m.start()] + "\n".join(script_bits) + "\n" + html[m.start():]
    else:
        html = html + "\n" + "\n".join(script_bits) + "\n"

    sources = [(SHIM, shim)] + [(ROOM_DIR + "/" + n, js) for n, js in scripts]
    return html, sources, len(styles), len(scripts)


# ---------------------------------------------------------------- syntax checks

NODE_CHECK = r"""
const fs = require('fs');
const vm = require('vm');
const list = JSON.parse(fs.readFileSync(0, 'utf8'));
let bad = 0;
for (const item of list) {
  const src = fs.readFileSync(item.path, 'utf8');
  try {
    if (item.kind === 'cjs') vm.compileFunction(src, ['module', 'exports', 'require'], { filename: item.name });
    else new vm.Script(src, { filename: item.name });
  } catch (e) {
    bad++;
    const where = (String(e.stack || '').split('\n')[0] || '');
    console.error('SYNTAX ' + item.name + ': ' + e.message + (where.indexOf(item.name) === 0 ? ' (' + where + ')' : ''));
  }
}
process.exit(bad ? 1 : 0);
"""


def node_bin():
    node = shutil.which("node")
    if not node:
        fail("node is not on PATH: cannot check syntax")
    return node


def check_sources(node, root, modules, room_sources):
    with tempfile.TemporaryDirectory() as tmp:
        items = []
        for rel in modules:
            if rel.endswith(".js"):
                items.append({"path": str(root / rel), "name": rel, "kind": "cjs"})
        for i, (name, src) in enumerate(room_sources):
            p = Path(tmp) / ("room-%03d.js" % i)
            p.write_text(src, encoding="utf-8")
            items.append({"path": str(p), "name": name, "kind": "script"})
        r = subprocess.run([node, "-e", NODE_CHECK], input=json.dumps(items), text=True,
                           capture_output=True)
        if r.returncode != 0:
            sys.stderr.write(r.stderr)
            fail("syntax errors in sources (see above)")
    return len(items)


def check_bundle(node, path):
    # main.js is CommonJS; check it under a .cjs name so a package.json "type" never changes the parse
    with tempfile.TemporaryDirectory() as tmp:
        p = Path(tmp) / "main.cjs"
        shutil.copyfile(path, p)
        r = subprocess.run([node, "--check", str(p)], text=True, capture_output=True)
        if r.returncode != 0:
            sys.stderr.write(r.stdout + r.stderr)
            fail("node --check failed on main.js")


# ---------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(description="Build main.js for the Casa plugin")
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent),
                    help="project root (default: the folder of build.py)")
    ap.add_argument("--dist", help="write main.js, manifest.json, styles.css into this folder "
                                   "instead of the project root (for test vaults or tests)")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    if not (root / ENTRY).is_file():
        fail(ENTRY + " is missing under " + str(root))
    node = node_bin()

    modules = collect_modules(root)
    room_html, room_sources, n_styles, n_scripts = build_room(root)
    checked = check_sources(node, root, modules, room_sources)

    entries = [module_entry(root, rel) for rel in modules]
    entries.append("%s: function (module) { module.exports = __casaRoomDoc; }" % json.dumps(ROOM_DOC_ID))
    room_literal = json.dumps(room_html, ensure_ascii=True)

    out = []
    out.append("/* Casa. Generated by build.py from src/. Edit the sources, not this file. */")
    out.append("(function () {")
    out.append("var __casaRoomDoc = " + room_literal + ";")
    out.append("var __casaFiles = {\n" + ",\n".join(entries) + "\n};")
    out.append(REGISTRY)
    out.append("var __casaMain = __casaLoad(%s);" % json.dumps(ENTRY))
    out.append("module.exports = __casaMain;")
    out.append("if (__casaMain && !__casaMain.default) { try { __casaMain.default = __casaMain; } catch (e) {} }")
    out.append("})();")
    bundle = "\n".join(out) + "\n"

    if args.dist:
        dist = Path(args.dist).resolve()
        dist.mkdir(parents=True, exist_ok=True)
    else:
        dist = root
    main_path = dist / "main.js"
    main_path.write_text(bundle, encoding="utf-8")
    check_bundle(node, main_path)

    if args.dist:
        for name in ("manifest.json", "styles.css"):
            src = root / name
            if src.is_file():
                shutil.copyfile(src, dist / name)
            else:
                warn(name + " is missing at the project root")

    shim_size = len((root / SHIM).read_bytes())
    print("modules: %d (%s)" % (len(modules), ", ".join(modules)))
    print("room: %d scripts, %d stylesheets, document %s (shim %s)"
          % (n_scripts, n_styles, kb(len(room_html.encode("utf-8"))), kb(shim_size)))
    print("syntax: %d files ok, main.js ok (node --check)" % checked)
    for name in RELEASE_FILES:
        p = dist / name
        if p.is_file():
            print("%-14s %s" % (name, kb(p.stat().st_size)))
    print("built %s%s" % (main_path, " with %d warning(s)" % len(warnings) if warnings else ""))


if __name__ == "__main__":
    main()
