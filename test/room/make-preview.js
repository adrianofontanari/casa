// Writes test/room-preview.html: the room markup from src/room/room.html, room.css,
// the dev mock bridge, then every script listed in src/room/order.txt, by relative path.
// Usage: node test/room/make-preview.js
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const ROOM = path.join(ROOT, 'src', 'room');
const order = fs.readFileSync(path.join(ROOM, 'order.txt'), 'utf8').split('\n')
  .map((l) => l.trim()).filter((l) => l && !l.startsWith('#')).map((l) => l.split(/\s+/)[0].replace(/^src\/room\//, ''));
const present = order.filter((n) => fs.existsSync(path.join(ROOM, n)));
const missing = order.filter((n) => !present.includes(n));
const html = fs.readFileSync(path.join(ROOM, 'room.html'), 'utf8');
const body = (/<body[^>]*>([\s\S]*)<\/body>/i.exec(html) || [, ''])[1].replace(/<!--[\s\S]*?-->/g, '').trim();
const out = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Casa room preview</title>
<!-- generated by test/room/make-preview.js, do not edit -->
<link rel="stylesheet" href="../src/room/room.css">
</head>
<body>
${body}
<script src="../src/room/dev/mock-bridge.js"></script>
${present.map((n) => `<script src="../src/room/${n}"></script>`).join('\n')}
</body>
</html>
`;
fs.writeFileSync(path.join(ROOT, 'test', 'room-preview.html'), out);
console.log('room-preview.html: ' + present.length + ' scripts' + (missing.length ? ', missing: ' + missing.join(', ') : ''));
